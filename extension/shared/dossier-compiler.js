export function compileSingleAuditToMarkdown(item) {
  if (!item || !item.result) return '';
  const result = item.result;
  const title = item.title || 'Course Material';
  const pageType = item.pageType || 'Web Page';
  const url = item.url || '';
  const timestamp = (item.timestamp ? new Date(item.timestamp) : new Date()).toLocaleString();

  let mdParts = [
    `# idstack Instructional Design Audit: ${title}\n\n`,
    `> **Audited Component:** ${pageType}  \n`
  ];
  if (url) mdParts.push(`> **Source URL:** [${url}](${url})  \n`);
  mdParts.push(
    `> **Date:** ${timestamp}  \n`,
    `> **Evaluator:** idstack Evidence-Based Course Design Engine (Manifest V3)\n\n`,
    `## Executive Summary\n\n`,
    `- **Bloom's Demand:** ${result.summary?.bloomsLevel || 'N/A'}\n`,
    `- **Constructive Alignment:** ${result.summary?.alignmentScore || 'N/A'}\n`,
    `- **Key Takeaway:** ${result.summary?.keyTakeaway || 'No summary provided.'}\n\n`
  );

  if (Array.isArray(result.findings) && result.findings.length > 0) {
    mdParts.push(`## Evidence-Based Findings & Recommendations\n\n`);
    mdParts.push(result.findings.map((f, idx) => {
      return `### ${idx + 1}. [${f.tier || 'T1'}] ${f.citation || 'Citation'}\n\n` +
             `- **Severity:** \`${(f.severity || 'info').toUpperCase()}\`\n` +
             `- **Observation:** ${f.observation || ''}\n` +
             `- **Empirical Evidence:** ${f.evidence || ''}\n` +
             `- **Actionable Recommendation:** ${f.recommendation || ''}\n\n`;
    }).join(''));
  }

  if (result.improvedDraft && result.improvedDraft.content) {
    mdParts.push(
      `## ${result.improvedDraft.title || 'Improved Draft & Alignment Matrix'}\n\n`,
      `${result.improvedDraft.content}\n\n`
    );
  }

  mdParts.push(`---\n*Generated by [idstack](https://github.com/savvides/idstack) — Evidence-Based Course Design.*`);
  return mdParts.join('');
}

export function compileDossierToMarkdown(dossierItems, courseTitle = 'Canvas Course') {
  if (!Array.isArray(dossierItems) || dossierItems.length === 0) {
    return `# idstack Course Audit Dossier: ${courseTitle}\n\n*No audit materials in dossier.*`;
  }

  const timestamp = new Date().toLocaleString();

  let mdParts = [
    `# idstack Course Audit Dossier: ${courseTitle}\n\n`,
    `> **Course:** ${courseTitle}  \n`,
    `> **Total Audited Materials:** ${dossierItems.length} components  \n`,
    `> **Compiled Date:** ${timestamp}  \n`,
    `> **Engine:** idstack Evidence-Based Instructional Design Co-Pilot\n\n`,
    `## Table of Audited Materials\n\n`,
    `| # | Component Title | Type | Bloom's Demand | Alignment Score |\n`,
    `| :--- | :--- | :--- | :--- | :--- |\n`
  ];

  mdParts.push(dossierItems.map((item, idx) => {
    const s = item.result?.summary || {};
    return `| ${idx + 1} | ${item.title || 'Untitled'} | ${item.pageType || 'Page'} | ${s.bloomsLevel || 'N/A'} | ${s.alignmentScore || 'N/A'} |\n`;
  }).join(''));

  mdParts.push(`\n---\n\n`);

  mdParts.push(dossierItems.map((item, idx) => {
    let sectionParts = [
      `## Section ${idx + 1}: ${item.title || 'Component'}\n\n`,
      `> **Type:** ${item.pageType || 'Page'} | **Source:** ${item.url || 'N/A'}\n\n`
    ];

    const r = item.result || {};
    sectionParts.push(
      `### Summary\n`,
      `- **Cognitive Demand:** ${r.summary?.bloomsLevel || 'N/A'}\n`,
      `- **Alignment Rating:** ${r.summary?.alignmentScore || 'N/A'}\n`,
      `- **Takeaway:** ${r.summary?.keyTakeaway || 'N/A'}\n\n`
    );

    if (Array.isArray(r.findings) && r.findings.length > 0) {
      sectionParts.push(`### Findings & Evidence\n\n`);
      sectionParts.push(r.findings.map((f, fIdx) => {
        return `#### ${idx + 1}.${fIdx + 1} [${f.tier || 'T1'}] ${f.citation || 'Citation'}\n` +
               `- **Observation:** ${f.observation || ''}\n` +
               `- **Evidence:** ${f.evidence || ''}\n` +
               `- **Recommendation:** ${f.recommendation || ''}\n\n`;
      }).join(''));
    }

    if (r.improvedDraft && r.improvedDraft.content) {
      sectionParts.push(
        `### ${r.improvedDraft.title || 'Revised Draft'}\n\n`,
        `${r.improvedDraft.content}\n\n`
      );
    }

    sectionParts.push(`---\n\n`);
    return sectionParts.join('');
  }).join(''));

  mdParts.push(`*Generated by [idstack](https://github.com/savvides/idstack) — Evidence-Based Course Design.*`);

  return mdParts.join('');
}
