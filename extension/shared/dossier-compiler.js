export function compileSingleAuditToMarkdown(item) {
  if (!item || !item.result) return '';
  const result = item.result;
  const title = item.title || 'Course Material';
  const pageType = item.pageType || 'Web Page';
  const url = item.url || '';
  const timestamp = (item.timestamp ? new Date(item.timestamp) : new Date()).toLocaleString();

  const md = [];
  md.push(`# idstack Instructional Design Audit: ${title}\n\n`);
  md.push(`> **Audited Component:** ${pageType}  \n`);
  if (url) md.push(`> **Source URL:** [${url}](${url})  \n`);
  md.push(`> **Date:** ${timestamp}  \n`);
  md.push(`> **Evaluator:** idstack Evidence-Based Course Design Engine (Manifest V3)\n\n`);

  md.push(`## Executive Summary\n\n`);
  md.push(`- **Bloom's Demand:** ${result.summary?.bloomsLevel || 'N/A'}\n`);
  md.push(`- **Constructive Alignment:** ${result.summary?.alignmentScore || 'N/A'}\n`);
  md.push(`- **Key Takeaway:** ${result.summary?.keyTakeaway || 'No summary provided.'}\n\n`);

  if (Array.isArray(result.findings) && result.findings.length > 0) {
    md.push(`## Evidence-Based Findings & Recommendations\n\n`);
    md.push(result.findings.map((f, idx) => {
      const fLines = [];
      fLines.push(`### ${idx + 1}. [${f.tier || 'T1'}] ${f.citation || 'Citation'}\n\n`);
      fLines.push(`- **Severity:** \`${(f.severity || 'info').toUpperCase()}\`\n`);
      fLines.push(`- **Observation:** ${f.observation || ''}\n`);
      fLines.push(`- **Empirical Evidence:** ${f.evidence || ''}\n`);
      fLines.push(`- **Actionable Recommendation:** ${f.recommendation || ''}\n\n`);
      return fLines.join('');
    }).join(''));
  }

  if (result.improvedDraft && result.improvedDraft.content) {
    md.push(`## ${result.improvedDraft.title || 'Improved Draft & Alignment Matrix'}\n\n`);
    md.push(`${result.improvedDraft.content}\n\n`);
  }

  md.push(`---\n*Generated by [idstack](https://github.com/savvides/idstack) — Evidence-Based Course Design.*`);
  return md.join('');
}

export function compileDossierToMarkdown(dossierItems, courseTitle = 'Canvas Course') {
  if (!Array.isArray(dossierItems) || dossierItems.length === 0) {
    return `# idstack Course Audit Dossier: ${courseTitle}\n\n*No audit materials in dossier.*`;
  }

  const timestamp = new Date().toLocaleString();
  const md = [];
  md.push(`# idstack Course Audit Dossier: ${courseTitle}\n\n`);
  md.push(`> **Course:** ${courseTitle}  \n`);
  md.push(`> **Total Audited Materials:** ${dossierItems.length} components  \n`);
  md.push(`> **Compiled Date:** ${timestamp}  \n`);
  md.push(`> **Engine:** idstack Evidence-Based Instructional Design Co-Pilot\n\n`);

  md.push(`## Table of Audited Materials\n\n`);
  md.push(`| # | Component Title | Type | Bloom's Demand | Alignment Score |\n`);
  md.push(`| :--- | :--- | :--- | :--- | :--- |\n`);
  md.push(dossierItems.map((item, idx) => {
    const s = item.result?.summary || {};
    return `| ${idx + 1} | ${item.title || 'Untitled'} | ${item.pageType || 'Page'} | ${s.bloomsLevel || 'N/A'} | ${s.alignmentScore || 'N/A'} |\n`;
  }).join(''));
  md.push(`\n---\n\n`);

  md.push(dossierItems.map((item, idx) => {
    const section = [];
    section.push(`## Section ${idx + 1}: ${item.title || 'Component'}\n\n`);
    section.push(`> **Type:** ${item.pageType || 'Page'} | **Source:** ${item.url || 'N/A'}\n\n`);

    const r = item.result || {};
    section.push(`### Summary\n`);
    section.push(`- **Cognitive Demand:** ${r.summary?.bloomsLevel || 'N/A'}\n`);
    section.push(`- **Alignment Rating:** ${r.summary?.alignmentScore || 'N/A'}\n`);
    section.push(`- **Takeaway:** ${r.summary?.keyTakeaway || 'N/A'}\n\n`);

    if (Array.isArray(r.findings) && r.findings.length > 0) {
      section.push(`### Findings & Evidence\n\n`);
      section.push(r.findings.map((f, fIdx) => {
        const fLines = [];
        fLines.push(`#### ${idx + 1}.${fIdx + 1} [${f.tier || 'T1'}] ${f.citation || 'Citation'}\n`);
        fLines.push(`- **Observation:** ${f.observation || ''}\n`);
        fLines.push(`- **Evidence:** ${f.evidence || ''}\n`);
        fLines.push(`- **Recommendation:** ${f.recommendation || ''}\n\n`);
        return fLines.join('');
      }).join(''));
    }

    if (r.improvedDraft && r.improvedDraft.content) {
      section.push(`### ${r.improvedDraft.title || 'Revised Draft'}\n\n`);
      section.push(`${r.improvedDraft.content}\n\n`);
    }

    section.push(`---\n\n`);
    return section.join('');
  }).join(''));

  md.push(`*Generated by [idstack](https://github.com/savvides/idstack) — Evidence-Based Course Design.*`);
  return md.join('');
}
